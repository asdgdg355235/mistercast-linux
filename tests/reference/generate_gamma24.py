#!/usr/bin/env python3
"""Generate the production tables and optionally the exhaustive test oracle."""
import argparse
import hashlib
import json
from decimal import Decimal as D, localcontext, ROUND_HALF_UP, ROUND_CEILING
from pathlib import Path

Q = (1 << 24) - 1
ROOT = Path(__file__).resolve().parents[2]


def curves(precision):
    with localcontext() as ctx:
        ctx.prec = precision
        exponent = D(12) / 5
        return ([(D(c) / 255) ** exponent for c in range(256)],
                [((D(c) + D('0.5')) / 255) ** exponent for c in range(255)])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-tables', action='store_true')
    parser.add_argument('--oracle', type=Path)
    args = parser.parse_args()
    decoded, boundaries = curves(80)
    with localcontext() as ctx:
        ctx.prec = 80
        lut = [int((v * Q).to_integral_value(rounding=ROUND_HALF_UP)) for v in decoded]
        thresholds = [int((v * 256 * Q).to_integral_value(rounding=ROUND_CEILING))
                      for v in boundaries]
        if args.write_tables or args.oracle:
            output = '// Generated by tests/reference/generate_gamma24.py using Decimal at 80 digits.\n'
            output += '// Generator SHA-256: ' + hashlib.sha256(Path(__file__).read_bytes()).hexdigest() + '\n'
            output += '#pragma once\n\n#include <array>\n#include <cstdint>\n\nnamespace mistercast::gamma24 {\n'
            for name, values in [('decode', lut), ('thresholds', thresholds)]:
                output += f'inline constexpr std::array<std::uint32_t, {len(values)}> {name}{{\n'
                for i in range(0, len(values), 8):
                    output += '    ' + ', '.join(f'{v}u' for v in values[i:i+8]) + ',\n'
                output += '};\n'
            header = ROOT / 'src/core/Gamma24Tables.h'
            if args.write_tables:
                header.write_text(output + '}\n')
            elif header.read_text() != output + '}\n':
                raise ValueError('Production table does not match its generator')
            vectors = [(0, 255, 128), (0, 1, 128), (0, 255, 1), (13, 29, 17),
                       (121, 129, 128), (17, 255, 0), (17, 255, 256), (128, 128, 241)]
            expected = []
            for a, b, w in vectors:
                mixed = (256 - w) * decoded[a] + w * decoded[b]
                expected.append([a, b, w, sum(mixed >= t * 256 for t in boundaries)])
            fixture = ROOT / 'tests/reference/gamma24_vectors.json'
            smoke = json.dumps({'decimal_digits': 80, 'vectors': expected}, indent=2) + '\n'
            if args.write_tables:
                fixture.write_text(smoke)
            elif fixture.read_text() != smoke:
                raise ValueError('Checked-in smoke vectors do not match the oracle')
        if args.oracle:
            # Integer comparisons retain 70 decimal places. Re-evaluate any
            # comparison close enough to be affected by truncation at 120 digits.
            scale = D(10) ** 70
            light = [int(v * scale) for v in decoded]
            cuts = [int(v * scale * 256) for v in boundaries]
            high_light, high_cuts = curves(120)
            table = bytearray(256 * 256 * 257)
            for a in range(256):
                for b in range(a, 256):
                    pos = (a * 256 + b) * 257
                    reverse = (b * 256 + a) * 257 + 256
                    mixed = light[a] * 256
                    step = light[b] - light[a]
                    code = a
                    for w in range(257):
                        while code < b and mixed >= cuts[code] - 256:
                            if abs(mixed - cuts[code]) <= 256:
                                with localcontext() as high:
                                    high.prec = 120
                                    if (256-w)*high_light[a] + w*high_light[b] < 256*high_cuts[code]:
                                        break
                            code += 1
                        table[pos + w] = table[reverse - w] = code
                        mixed += step
            args.oracle.write_bytes(table)


if __name__ == '__main__':
    main()
